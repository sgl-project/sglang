"""H3 image request: references (image_path) select edit, none select t2i."""

from dataclasses import dataclass, field
from typing import Any

from sglang.multimodal_gen.configs.sample.sampling_params import SamplingParams
from sglang.multimodal_gen.configs.task_type import DataType
from sglang.multimodal_gen.runtime.pipelines_core.stages.model_specific_stages.minimax_h3.request_validation import (
    minimax_h3_validate_canonical_request,
)
from sglang.multimodal_gen.runtime.pipelines_core.stages.model_specific_stages.minimax_h3.resolved_plan import (
    MINIMAX_H3_CANONICAL_REQUEST_EXTRA_KEY,
    MINIMAX_H3_RESOLVED_PLAN_EXTRA_KEY,
    minimax_h3_resolve_plan,
)


@dataclass
class MiniMaxH3ImageSamplingParams(SamplingParams):
    """One request, one image, generated by a PDD release.

    The release (``_minimax_h3.pdd_fused_heads`` in model_index.json) has one
    fused output head per step, so it runs exactly that many steps, also the
    default. The checkpoint is CFG-distilled and runs one positive branch per
    step: ``negative_prompt`` is rejected and ``guidance_scale`` /
    ``true_cfg_scale`` accept only 1 (no guidance). A no-prompt instance is a
    defaults template for the shared sampling factory. All noise comes from one
    generator per request seeded with ``seed`` on ``generator_device`` (see
    minimax_h3/image_noise.py). A request below ``min_generation_area`` pixels
    is generated on a larger canvas and resized back to width x height (see
    minimax_h3/image_canvas.py).
    """

    data_type: DataType = DataType.IMAGE
    prompt: str | None = None
    negative_prompt: str | None = None
    seed: int = field(default=0, metadata={"batch_sig_exclude": True})
    num_frames: int = 1
    num_inference_steps: int | None = None
    task: str | None = None
    # Pixel area the request is generated on at least (minimax_h3/image_canvas.py);
    # the image is resized back to width x height. None takes the pipeline
    # config's min_generation_area once the server adjusts the request.
    min_generation_area: int | None = None

    @classmethod
    def image_request_extra_fields(cls) -> frozenset[str]:
        return frozenset({"min_generation_area"})

    @classmethod
    def default_image_output_format(cls) -> str:
        return "png"

    def _reference_paths(self) -> list[str]:
        if isinstance(self.image_path, str):
            return [self.image_path]
        return self.image_path if isinstance(self.image_path, list) else []

    def _canonical_request(self) -> dict[str, Any]:
        paths = self._reference_paths()
        target = {"width": self.width, "height": self.height}
        if self.min_generation_area is not None:
            target["min_generation_area"] = self.min_generation_area
        request = {
            "task": "edit" if paths else "t2i",
            "prompt": self.prompt,
            "conditions": [
                {"role": "reference", "type": "image", "uri": path} for path in paths
            ],
            "target": target,
            "seed": self.seed,
        }
        # Factory hooks re-enter here; validate each distinct request once.
        if getattr(self, "_canonical_source", None) != request:
            self._canonical = minimax_h3_validate_canonical_request(**request)
            self._canonical_source = request
        return self._canonical

    def _reject_guidance(self) -> None:
        # No negative branch exists, so these fields cannot change the output.
        if self.negative_prompt is not None:
            raise ValueError(
                "negative_prompt is not supported: MiniMax H3 image runs one "
                "positive branch (CFG-distilled checkpoint)"
            )
        for name in ("guidance_scale", "true_cfg_scale"):
            value = getattr(self, name)
            if value is not None and (isinstance(value, bool) or value != 1):
                raise ValueError(
                    "MiniMax H3 image runs one positive branch (CFG-distilled "
                    f"checkpoint): {name} must be 1, got {value!r}"
                )

    def _validate(self) -> None:
        if self.num_frames != 1 or self.num_outputs_per_prompt != 1:
            raise ValueError("MiniMax H3 image produces exactly one image per request")
        self._reject_guidance()
        if self.prompt is not None:
            # The release fixes the step count (resolved in _adjust); a user
            # value must at least be a step count.
            steps = self.num_inference_steps
            if steps is not None and (
                isinstance(steps, bool) or not isinstance(steps, int) or steps < 1
            ):
                raise ValueError(
                    "MiniMax H3 image requires an integer num_inference_steps "
                    f">= 1, got {steps!r}"
                )
            # The size rules depend on min_generation_area; an unset area is
            # resolved from the server in _adjust, which validates the request.
            if self.min_generation_area is not None:
                self._canonical_request()
        super()._validate()
        if self.quality not in ("exact", "lossless"):
            raise ValueError("MiniMax H3 image supports quality='exact' or 'lossless'")
        if (
            self.enable_teacache
            or self.enable_cache_dit
            or self.enable_spectrum
            or self.skip_softmax_params is not None
        ):
            raise ValueError("MiniMax H3 image does not support approximate caching")

    def _adjust(self, server_args) -> None:
        # Do not call the video/visual adjuster: it strips text and changes shape.
        if self.prompt is not None:
            steps = server_args.pipeline_config.release_pdd_steps()
            # Check only a user-set count: a count the factory merge carried
            # over from the defaults template is replaced (any non-None count
            # is checked when explicit fields are not recorded).
            explicit_fields = getattr(self, "_explicit_fields", None)
            if (
                explicit_fields is not None
                and "num_inference_steps" not in explicit_fields
            ) or self.num_inference_steps is None:
                self.num_inference_steps = steps
            elif self.num_inference_steps != steps:
                raise ValueError(
                    f"this MiniMax H3 PDD release has {steps} fused output "
                    f"heads, so num_inference_steps must be {steps} or omitted, "
                    f"got {self.num_inference_steps!r}"
                )
        server_area = server_args.pipeline_config.min_generation_area
        if self.min_generation_area is None:
            self.min_generation_area = server_area
        elif server_area is None:
            raise ValueError(
                "min_generation_area is disabled on this server (the pipeline "
                "config sets min_generation_area to null)"
            )
        self._validate()
        self.task = self._canonical_request()["task"]
        self.task_type = self.resolve_task_type(server_args.pipeline_config)
        self._adjust_output_path(server_args)
        if not server_args.comfyui_mode:
            self._set_output_file_name()

    def build_request_extra(self) -> dict[str, Any]:
        canonical = self._canonical_request()
        extra = super().build_request_extra()
        extra[MINIMAX_H3_CANONICAL_REQUEST_EXTRA_KEY] = canonical
        extra[MINIMAX_H3_RESOLVED_PLAN_EXTRA_KEY] = minimax_h3_resolve_plan(canonical)
        return extra

    def prepare_synthetic_warmup_request_for_queue(
        self, req: Any, server_args: Any
    ) -> None:
        warmup_steps = req.num_inference_steps
        self.num_inference_steps = server_args.pipeline_config.release_pdd_steps()
        self.task_type = None
        self._adjust(server_args)
        req.extra.update(self.build_request_extra())
        # Only synthetic warmup may use a prefix. Compile's serving-path
        # prewarm is a real forward and must execute every fused PDD head.
        if req.is_warmup:
            req.num_inference_steps = min(warmup_steps, self.num_inference_steps)

    def apply_request_extra(self, req: Any) -> None:
        super().apply_request_extra(req)
        self.task = req.extra[MINIMAX_H3_RESOLVED_PLAN_EXTRA_KEY].task


__all__ = ["MiniMaxH3ImageSamplingParams"]
