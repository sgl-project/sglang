def source(base, vendor, route):
    if route not in SOURCE_SHA256:
        raise ValueError("route must be small or large")
    for text, expected in ((base, BASE_SHA256), (vendor, VENDOR_SHA256)):
        if hashlib.sha256(text.encode()).hexdigest() != expected:
            raise ValueError("unqualified legacy selector/vendor source")
    # Override inherited logical-ID emission in all radix/tie fallbacks.
    start = vendor.index("    @cute.jit\n    def _ballot_pair_emit(")
    end = vendor.index("    # ------------------------------------------------------------------", start)
    helper = vendor[start:end].replace("_ballot_pair_emit", "_physical_ballot_pair_emit")
    helper = helper.replace("s_scal, lane):", "s_scal, lane, ptable, tbase):")
    helper = helper.replace("= idv\n", "= ptable[tbase + (idv >> cutlass.Int32(6))] * cutlass.Int32(64) + (idv & cutlass.Int32(63))\n")
    text = replace(base, "    @cute.kernel\n    def kern(", helper + "    @cute.kernel\n    def kern(")
    text = text.replace("self._ballot_pair_emit(", "self._physical_ballot_pair_emit(")
    text = text.replace("out_row, s_scal, lane\n", "out_row, s_scal, lane, ptable, tbase\n")
    text = text.replace("                                    lane,\n", "                                    lane, ptable, tbase,\n")

    # Preserve the original publication/fallback block under an R1 local branch.
    anchor = "                if cutlass.const_expr(self.split):\n                    pubn = myn\n"
    start = text.index(anchor) + len("                if cutlass.const_expr(self.split):\n")
    end = text.index("                else:\n                    # ---- non-split verify + rung ladder ----\n", start)
    old = text[start:end]
    gate = """                    local_fast = cutlass.Int32(0)
                    if s_cert[3] == cutlass.Int32(1):
                        if cert_fast != cutlass.Int32(0):
                            if expected_pass <= cutlass.Int32(CMPB) and myn <= cutlass.Int32(CMPB):
                                local_fast = cutlass.Int32(1)
"""
    text = text[:start] + gate + textwrap.indent(LOCAL_BRANCH.lstrip(), " " * 20) + textwrap.indent(old, " " * 4) + text[end:]

    text = text.replace("        npages: cutlass.Int32,\n", "        npages: cutlass.Int32,\n        active_batch: cute.Tensor,\n")
    if text.count("        active_batch: cute.Tensor,\n") != 2:
        raise ValueError("active-count signature drift")
    text = replace(text, "            npages,\n", "            npages,\n            active_batch,\n")
    start = text.index("        bx, by, _ = cute.arch.block_idx()  # 2-D grid (part, row)\n")
    end = text.index("        # ================= per-row varlen prologue", start)
    text = text[:start] + textwrap.indent(DEVICE_GEOMETRY.lstrip(), " " * 8) + text[end:]
    text = replace(text, "            kvl = kv_lens[req]\n", """            kvl = cutlass.Int32(0)
            if inactive == cutlass.Int32(0):
                kvl = kv_lens[req]
""")
    text = replace(text, "        if part < R:\n", "        if part < R and inactive == cutlass.Int32(0):\n")
    start = text.index("            if cutlass.const_expr(self.r_const == 37):\n")
    end = text.index("            n_row = nv\n", start)
    text = text[:start] + text[end:]
    start = text.index("                    Q = (n4v + cutlass.Int32(self.r_const - 1))")
    end = text.index("                else:\n", start)
    text = text[:start] + "                    Q = (n4v + R - cutlass.Int32(1)) >> part_shift\n" + text[end:]
    text = replace(text, "                        if cutlass.const_expr(self.r_const > 1):\n",
                   "                        if s_cert[3] > cutlass.Int32(1):\n")
    text = replace(text, "                s_cert[2] = cutlass.Int32(0)\n",
                   "                s_cert[2] = cutlass.Int32(0)\n"
                   "                s_cert[3] = R  # immutable runtime part count\n")
    text = replace(text, "                        if cutlass.Int32(pk >> cutlass.Int64(32)) == R - cutlass.Int32(1):\n",
                   "                        if cutlass.Int32(pk >> cutlass.Int64(32)) == s_cert[3] - cutlass.Int32(1):\n")
    text = replace(text, """            if tidx == cutlass.Int32(0):
                drow = row * cutlass.Int32(self.r_const) + part
                diagnostics[drow, 0] = cert_fast
""", """            # One diagnostic record per storage row. All row parts derive
            # identical certificate/threshold fields; part zero owns publication.
            if tidx == cutlass.Int32(0) and part == cutlass.Int32(0):
                drow = row
                diagnostics[drow, 0] = cert_fast
""")
    start = text.index("        else:\n            if tidx < cutlass.Int32(6):\n")
    end = text.index("    # ------------------------------------------------------------------\n    # host launcher", start)
    text = text[:start] + text[end:]
    text = replace(text, ").launch(grid=(R, b, 1),", ").launch(grid=(128, 1, 1),")
    text = text.replace("# host launcher (grid dim3(R, b); MINB wall via min_blocks_per_mp)",
                        "# host launcher (fixed 128 CTAs; active/R ownership is device-only)")
    if "self.r_const" in text or "_certificate_failure_trap" in text:
        raise ValueError("static row-part dependency or certificate-only source")

    if route == "small":
        start = text.index("            h0 = cutlass.Int32(0)\n")
        end = text.index("            hincl =", start)
        text = text[:start] + """            hh = cute.make_rmem_tensor((2,), cutlass.Int32)
            hs = cutlass.Int32(0)
            for hi in cutlass.range_constexpr(2):
                hv = cutlass.Int32(0)
                if short == cutlass.Int32(0):
                    hv = histogram[hbase + tidx * cutlass.Int32(2) + cutlass.Int32(hi)]
                hh[hi] = hv
                hs = hs + hv
""" + text[end:]
        text = replace(text, "            warp_total = s_cbuf[lane]\n",
                       "            warp_total = cutlass.Int32(0)\n"
                       "            if lane < cutlass.Int32(NW):\n"
                       "                warp_total = s_cbuf[lane]\n")
        start = text.index("            run0 = hbefore + hincl - hs\n")
        end = text.index("            cute.arch.barrier()  # crossing", start)
        text = text[:start] + """            running = hbefore + hincl - hs
            if short == cutlass.Int32(0):
                for hi in cutlass.range_constexpr(2):
                    after = running + hh[hi]
                    if running <= k and k < after:
                        s_cbuf[NW + 0] = tidx * cutlass.Int32(2) + cutlass.Int32(hi)
                        s_cbuf[NW + 1] = running
                        s_cbuf[NW + 2] = hh[hi]
                    running = after
                if tidx == cutlass.Int32(BLK - 1):
                    s_cbuf[NW + 3] = running
""" + text[end:]

    # Device guards cover the complete bodies, including inactive-row cleanup.
    start = text.index("        BLK = self.blk\n")
    end = text.index("    # ------------------------------------------------------------------\n    # host launcher", start)
    condition = "!=" if route == "small" else "=="
    guard = """        route_active = active_batch[0]
        route_small = cutlass.Int32(0)
        if route_active > cutlass.Int32(0) and route_active <= cutlass.Int32(8):
            if route_active <= cutlass.Int32(logits.shape[0]):
                route_small = cutlass.Int32(1)
"""
    text = text[:start] + guard + f"        if route_small {condition} cutlass.Int32(0):\n" + textwrap.indent(text[start:end], " " * 4) + text[end:]
    compile(text, f"fused_{route}.py", "exec")
    digest = hashlib.sha256(text.encode()).hexdigest()
    if digest != SOURCE_SHA256[route]:
        raise ValueError(f"qualified {route} source mismatch: {digest}")
    return text
