"""Reproduce the qualified V6 selectors from the unchanged legacy 1024-bin source.

The generated bytes must match the artifacts used in all 80 current-main runs.
These transforms add exact-fallback physical IDs, R1 shared candidates, and
fixed-128-CTA device row/part routing. Both full exact fallback branches remain.
No CuTe import or GPU access is needed to generate/check the sources.
"""
import hashlib
import textwrap

BASE_SHA256 = "faa13c98f6d59eb74961e3649b1175b89c9976c4d22a2239a3d560112600b2c4"
VENDOR_SHA256 = "dceaeec021126b7a72e4a9428d3e4d8e014e1d8d211f063396cf0f011f572195"
SOURCE_SHA256 = {
    "small": "0574e383697ccdec76f6a3c18fc4e6e060a73c8955c1736da4ffeba99898d561",
    "large": "f200bdabf3aea42dfc4d031a7637de3e45b8662c524f65ce42b11792c8c7737c",
}


def replace(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"fused source anchor count != 1: {old[:100]!r}")
    return text.replace(old, new, 1)


