class SailFlashMLABackend(FlashMLABackend):
    """FlashMLA backend running on the SAIL FlashMLA build.

    SAIL's ``get_mla_metadata`` returns a lazily initialized scheduler
    metadata object instead of (tile_scheduler_metadata, num_splits) tensors;
    the scheduling plan is generated by the first kernel call that consumes
    it. The model also feeds the absorbed q/k split into nope and rope parts
    (``q_rope`` / ``k_rope``), which are concatenated here.
    """

    def __init__(self, model_runner: ModelRunner, **kwargs):
        super().__init__(model_runner, **kwargs)
        # FlashMLABackend leaves the translator to bind_and_verify_backends,
        # which only reaches top-level backends; on SAIL this instance is wrapped
        # by SailHybridAttnBackend, so wire it here. Runners without the unified
        # pool (predating the translator) keep the triton path below.
        self.kv_index_translator = getattr(model_runner, "kv_index_translator", None)
        if self.is_fp8_kvcache:
            raise NotImplementedError(
                "FP8 KV cache is not supported by FlashMLA on SAIL."
            )

    def _call_get_mla_metadata(self, *args, **kwargs):
        return get_mla_metadata(*args, **kwargs)

    def _call_flash_mla_with_kvcache(self, **kwargs):
        return flash_mla_with_kvcache(**kwargs)

    def _apply_decode_target_verify_metadata(
        self,
        plan: KVLocPlan,
        bs: int,
        req_pool_indices: torch.Tensor,
        seq_lens: torch.Tensor,
        seq_lens_cpu: Optional[torch.Tensor],
        forward_mode: ForwardMode,
    ):
        seq_lens = seq_lens[:bs]
        seq_lens_cpu = seq_lens_cpu[:bs] if seq_lens_cpu is not None else None

        if forward_mode.is_target_verify():
            seq_lens = seq_lens + self.num_draft_tokens
            if seq_lens_cpu is not None:
                seq_lens_cpu = seq_lens_cpu + self.num_draft_tokens

        if seq_lens_cpu is not None:
            max_seqlen_pad = triton.cdiv(seq_lens_cpu.max().item(), PAGE_SIZE)
        else:
            max_seqlen_pad = self.cuda_graph_kv_indices.shape[1]

        translator = self.kv_index_translator
        if translator is not None and translator.reads_are_translated:
            assert self.page_size == PAGE_SIZE
            translator.copy_page_table(plan, out=self.cuda_graph_kv_indices[:bs])
        else:
            create_flashmla_kv_indices_triton[
                (
                    bs,
                    get_num_kv_index_blocks_flashmla(
                        self.cuda_graph_kv_indices.stride(0), PAGE_SIZE
                    ),
                )
            ](
                self.req_to_token,
                req_pool_indices[:bs],
                seq_lens,
                None,
                self.cuda_graph_kv_indices,
                self.req_to_token.stride(0),
                self.cuda_graph_kv_indices.stride(0),
            )

        q_head_mult = (
            self.num_draft_tokens
            if forward_mode.is_target_verify() or forward_mode.is_draft_extend_v2()
            else 1
        )
        # The scheduler metadata object is filled in by the kernel itself, so
        # there are no tensors to copy into static graph buffers.
        sched_meta, _ = self._call_get_mla_metadata(
            seq_lens.to(torch.int32),
            q_head_mult * self.num_q_heads,
            1,
            is_fp8_kvcache=False,
        )

        seq_lens_k = None
        if forward_mode.is_draft_extend_v2():
            # The graph kernel binds this static buffer; refresh per replay.
            self.cuda_graph_draft_extend_seq_lens_k[:bs].copy_(seq_lens)
            seq_lens_k = self.cuda_graph_draft_extend_seq_lens_k[:bs]

        self.forward_metadata = FlashMLADecodeMetadata(
            sched_meta,
            None,
            self.cuda_graph_kv_indices[:bs, :max_seqlen_pad],
            seq_lens_k,
        )

    def init_forward_metadata_in_graph(self, forward_batch: ForwardBatch):
        # Reset the scheduler metadata before capture so that its lazy
        # initialization in the first kernel call is recorded into the graph.
        if isinstance(self.forward_metadata, FlashMLADecodeMetadata):
            assert self.forward_metadata.flashmla_metadata is not None
            self.forward_metadata.flashmla_metadata.have_initialized = False

    def _absorb_rope(
        self,
        q: torch.Tensor,
        k: torch.Tensor,
        layer: RadixAttention,
        forward_batch: ForwardBatch,
        save_kv_cache: bool,
        q_rope: Optional[torch.Tensor],
        k_rope: Optional[torch.Tensor],
    ):
        """Write split k and concat split q; returns (q, save_kv_cache)."""
        if k_rope is not None:
            if save_kv_cache and k is not None:
                self.token_to_kv_pool.set_mla_kv_buffer(
                    layer, KVWriteLoc.for_batch(forward_batch), k, k_rope
                )
            save_kv_cache = False
        if q_rope is not None:
            q = concat_mla_absorb_q_general(
                q.view(-1, layer.tp_q_head_num, layer.v_head_dim),
                q_rope.view(-1, layer.tp_q_head_num, layer.head_dim - layer.v_head_dim),
            )
        return q, save_kv_cache

    def forward_decode(
        self,
        q: torch.Tensor,
        k: torch.Tensor,
        v: torch.Tensor,
        layer: RadixAttention,
        forward_batch: ForwardBatch,
        save_kv_cache: bool = True,
        q_rope: Optional[torch.Tensor] = None,
        k_rope: Optional[torch.Tensor] = None,
    ):
        q, save_kv_cache = self._absorb_rope(
            q, k, layer, forward_batch, save_kv_cache, q_rope, k_rope
        )
        return super().forward_decode(q, k, v, layer, forward_batch, save_kv_cache)

    def forward_extend(
        self,
        q: torch.Tensor,
        k: torch.Tensor,
        v: torch.Tensor,
        layer: RadixAttention,
        forward_batch: ForwardBatch,
        save_kv_cache: bool = True,
        q_rope: Optional[torch.Tensor] = None,
        k_rope: Optional[torch.Tensor] = None,
    ):
        if forward_batch.forward_mode == ForwardMode.EXTEND:
            return FlashInferMLAAttnBackend.forward_extend(
                self,
                q,
                k,
                v,
                layer,
                forward_batch,
                save_kv_cache,
                q_rope=q_rope,
                k_rope=k_rope,
            )
        q, save_kv_cache = self._absorb_rope(
            q, k, layer, forward_batch, save_kv_cache, q_rope, k_rope
        )
        return super().forward_extend(q, k, v, layer, forward_batch, save_kv_cache)


class SailFlashMLAMultiStepDraftBackend(FlashMLAMultiStepDraftBackend):
    def __init__(
        self,
        model_runner: ModelRunner,
        topk: int,
        speculative_num_steps: int,
    ):
        if topk > 1:
            raise ValueError(
                "Currently FlashMLA only supports topk=1 for speculative decoding"
            )
        self.topk = topk
        self.speculative_num_steps = speculative_num_steps
        self.kv_index_translator = model_runner.kv_index_translator
        max_bs = model_runner.req_to_token_pool.size * self.topk
        self.kv_indptr = torch.zeros(
            (
                self.speculative_num_steps,
                max_bs + 1,
            ),
            dtype=torch.int32,
            device=model_runner.device,
        )

        self.attn_backends = []
        for i in range(self.speculative_num_steps - 1):
            self.attn_backends.append(
                SailFlashMLABackend(
                    model_runner,
                    skip_prefill=True,
                    kv_indptr_buf=self.kv_indptr[i],
                    kv_last_page_len_buf=None,
                )
            )
