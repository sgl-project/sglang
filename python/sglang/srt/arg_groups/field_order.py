"""The order ``ServerArgs`` presents its fields in, frozen.

A dataclass turns field order into a positional constructor signature, and
``ServerArgs(model_path, tokenizer_path)`` is a call an out-of-tree caller can
already have written. Collecting whole namespaces groups fields that used to be
interleaved, so without this the second positional argument would quietly land
on a different field -- ``load_format="/tmp/tokenizer"`` instead of
``tokenizer_path``, which then selects an invalid model loader rather than
failing.

So the order is stated here rather than left to fall out of how the
declarations are grouped. It is a compatibility record, not a place to express
anything: the namespace a field belongs to is the module it is declared in, and
nothing reads this except ``collect_input_fields``.

A field not listed here goes after everything that is, in declaration order.
That is the only backward-compatible position for a new field anyway, so a new
declaration needs no edit here -- and appending a name is what freezes it.
"""

