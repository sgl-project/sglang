//! Seeded HTTP chat fuzz smoke tests; no model, GPU, or network downloads.
//!
//! Run with `cargo test --locked --test proxy chat_routing::fuzz_smoke:: -- --ignored`.
//! Failures print the seed, case index, and complete input. Replay the same run with
//! `SGL_ROUTER_FUZZ_SEED=<seed>`; `SGL_ROUTER_FUZZ_CASES` defaults to 64 (maximum 256).
//! This is generated integration coverage, not coverage-guided fuzzing. It drives
//! the legacy regular HTTP route, with real outbound HTTP to a local mock engine.
//! Mock body frames may be coalesced by HTTP; they are not TCP packet boundaries.
//! Early disconnects, PD, and reorg routing are follow-ups to this first slice.

use super::*;
use axum::extract::State;
use axum::routing::post;
use bytes::Bytes;
use rand::{rngs::StdRng, Rng, SeedableRng};
use std::collections::VecDeque;
use std::sync::Mutex;
use tokio::sync::oneshot;
use tokio::task::JoinHandle;

const CASE_TIMEOUT: Duration = Duration::from_secs(2);
const RUN_TIMEOUT: Duration = Duration::from_secs(30);
const GOOD_RESPONSE: &[u8] = br#"{"choices":[{"message":{"role":"assistant","content":"ok"}}]}"#;

#[derive(Clone, Debug)]
struct Reply {
    streaming: bool,
    chunks: Vec<Vec<u8>>,
}

impl Reply {
    fn good() -> Self {
        Self {
            streaming: false,
            chunks: vec![GOOD_RESPONSE.to_vec()],
        }
    }
}

#[derive(Clone)]
struct Script {
    replies: Arc<Mutex<VecDeque<Reply>>>,
    requests: Arc<Mutex<Vec<Bytes>>>,
}

/// Unlike the static mock, this serves a sequence of owned response bodies so
/// generated bytes and the recovery request use the very same worker instance.
struct ScriptedWorker {
    url: String,
    script: Script,
    shutdown: Option<oneshot::Sender<()>>,
    task: JoinHandle<std::io::Result<()>>,
}

impl ScriptedWorker {
    async fn start(replies: Vec<Reply>) -> Self {
        async fn chat(State(script): State<Script>, body: Bytes) -> axum::response::Response {
            script.requests.lock().unwrap().push(body);
            let reply = script
                .replies
                .lock()
                .unwrap()
                .pop_front()
                .expect("unexpected upstream request");
            let frames = reply
                .chunks
                .into_iter()
                .map(|chunk| Ok::<_, std::io::Error>(Bytes::from(chunk)));
            axum::response::Response::builder()
                .header(
                    "content-type",
                    if reply.streaming {
                        "text/event-stream"
                    } else {
                        "application/json"
                    },
                )
                .body(Body::from_stream(futures::stream::iter(frames)))
                .unwrap()
        }
        let script = Script {
            replies: Arc::new(Mutex::new(replies.into())),
            requests: Arc::new(Mutex::new(Vec::new())),
        };
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let url = format!("http://{}", listener.local_addr().unwrap());
        let app = axum::Router::new()
            .route("/v1/chat/completions", post(chat))
            .with_state(script.clone());
        let (shutdown, rx) = oneshot::channel();
        let task = tokio::spawn(async move {
            axum::serve(listener, app)
                .with_graceful_shutdown(async {
                    let _ = rx.await;
                })
                .await
        });
        Self {
            url,
            script,
            shutdown: Some(shutdown),
            task,
        }
    }

    async fn stop(mut self) {
        let _ = self.shutdown.take().unwrap().send(());
        tokio::time::timeout(CASE_TIMEOUT, &mut self.task)
            .await
            .expect("mock shutdown hung")
            .expect("mock task panicked")
            .expect("mock server failed");
        assert!(
            self.script.replies.lock().unwrap().is_empty(),
            "not all scripted responses were used"
        );
    }
}

impl Drop for ScriptedWorker {
    fn drop(&mut self) {
        // Also runs when a case fails or the enclosing timeout drops its future.
        self.task.abort();
    }
}

fn run_config() -> (u64, usize) {
    let seed = std::env::var("SGL_ROUTER_FUZZ_SEED")
        .map(|s| s.parse().expect("seed must be a u64"))
        .unwrap_or(50045);
    let cases = std::env::var("SGL_ROUTER_FUZZ_CASES")
        .map(|s| s.parse().expect("cases must be an integer"))
        .unwrap_or(64);
    assert!(
        (1..=256).contains(&cases),
        "cases must be between 1 and 256"
    );
    (seed, cases)
}

fn request(streaming: bool, content: &str) -> Vec<u8> {
    serde_json::to_vec(&serde_json::json!({
        "model": "tiny", "messages": [{"role": "user", "content": content}], "stream": streaming,
    }))
    .unwrap()
}

async fn exchange(app: &axum::Router, body: Vec<u8>) -> (StatusCode, Bytes) {
    let response = app
        .clone()
        .oneshot(
            Request::builder()
                .method("POST")
                .uri("/v1/chat/completions")
                .header("content-type", "application/json")
                .body(Body::from(body))
                .unwrap(),
        )
        .await
        .unwrap();
    let status = response.status();
    // Complete mock bodies must be relayed completely. Accepting any body error
    // here would hide failures, including panics caught by the SSE pump.
    let bytes = response
        .into_body()
        .collect()
        .await
        .expect("router response body failed")
        .to_bytes();
    (status, bytes)
}

async fn recover(app: &axum::Router, ctx: &AppContext) {
    let (status, body) = exchange(app, request(false, "recovery")).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(body.as_ref(), GOOD_RESPONSE);
    loop {
        let workers_idle = ctx
            .registry
            .workers_for(&ModelId("tiny".into()))
            .iter()
            .all(|w| w.router_inflight_load() == 0);
        if workers_idle && ctx.router_inflight_load.inflight_count() == 0 {
            break;
        }
        tokio::task::yield_now().await;
    }
}

#[tokio::test]
#[ignore = "run explicitly in the time-limited HTTP chat fuzz CI step"]
async fn generated_requests_recover() {
    let (seed, cases) = run_config();
    let mut rng = StdRng::seed_from_u64(seed);
    tokio::time::timeout(RUN_TIMEOUT, async {
        for index in 0..cases {
            let content: String = (0..rng.gen_range(0..64))
                .map(|_| char::from(rng.gen_range(32u8..127)))
                .collect();
            let mut body = request(false, &content);
            let invalid = index % 4 != 0;
            match index % 4 {
                1 => {
                    body.truncate(rng.gen_range(0..body.len()));
                }
                2 => {
                    body = vec![b'['];
                    body.extend((0..rng.gen_range(0..128)).map(|_| rng.gen::<u8>()));
                    body.push(0xff);
                }
                3 => {
                    body = serde_json::to_vec(&serde_json::json!([content])).unwrap();
                }
                _ => (),
            }
            eprintln!("request seed={seed} case={index} invalid={invalid} body={body:?}");
            tokio::time::timeout(CASE_TIMEOUT, async {
                let worker =
                    ScriptedWorker::start(vec![Reply::good(); if invalid { 1 } else { 2 }]).await;
                let ctx = build_ctx_with_worker(&worker.url);
                let app = build_router(ctx.clone());
                let (status, _) = exchange(&app, body).await;
                assert_eq!(
                    status,
                    if invalid {
                        StatusCode::BAD_REQUEST
                    } else {
                        StatusCode::OK
                    }
                );
                recover(&app, &ctx).await;
                assert_eq!(
                    worker.script.requests.lock().unwrap().len(),
                    if invalid { 1 } else { 2 }
                );
                worker.stop().await;
            })
            .await
            .expect("generated request case hung");
        }
    })
    .await
    .expect("request fuzz run exceeded its time budget");
}

#[tokio::test]
#[ignore = "run explicitly in the time-limited HTTP chat fuzz CI step"]
async fn generated_responses_preserve_bytes_and_recover() {
    let (seed, cases) = run_config();
    let mut rng = StdRng::seed_from_u64(seed);
    tokio::time::timeout(RUN_TIMEOUT, async {
        for index in 0..cases {
            let streaming = index % 2 == 0;
            let payload = match index % 6 {
                0 => "data: {\"choices\":[{\"delta\":{\"content\":\"你好🌍\"}}]}\n\ndata: [DONE]\n\n".as_bytes().to_vec(),
                1 => GOOD_RESPONSE.to_vec(),
                2 => b"data: {not json}\n\ninvalid SSE\r\ndata: [DONE]".to_vec(),
                3 => b"{\"choices\":[".to_vec(),
                _ => (0..rng.gen_range(0..512)).map(|_| rng.gen::<u8>()).collect(),
            };
            let mut chunks = Vec::new();
            let mut offset = 0;
            while offset < payload.len() {
                let end = (offset + rng.gen_range(1..=16)).min(payload.len());
                chunks.push(payload[offset..end].to_vec());
                offset = end;
            }
            eprintln!("response seed={seed} case={index} streaming={streaming} payload={payload:?} chunks={chunks:?}");
            tokio::time::timeout(CASE_TIMEOUT, async {
                let worker = ScriptedWorker::start(vec![
                    Reply { streaming, chunks: vec![payload.clone()] },
                    Reply { streaming, chunks },
                    Reply::good(),
                ]).await;
                let ctx = build_ctx_with_worker(&worker.url);
                let app = build_router(ctx.clone());
                for _ in 0..2 {
                    let (status, received) = exchange(&app, request(streaming, "generated response")).await;
                    assert_eq!(status, StatusCode::OK);
                    // Regular HTTP forwarding is opaque: invalid upstream JSON/SSE
                    // is not necessarily a router-level 4xx/502.
                    assert_eq!(received.as_ref(), payload);
                }
                recover(&app, &ctx).await;
                assert_eq!(worker.script.requests.lock().unwrap().len(), 3);
                worker.stop().await;
            }).await.expect("generated response case hung");
        }
    }).await.expect("response fuzz run exceeded its time budget");
}
