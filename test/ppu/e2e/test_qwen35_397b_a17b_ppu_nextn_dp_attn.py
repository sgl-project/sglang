import os
import unittest

from sglang.srt.utils import kill_process_tree
from sglang.test.kits.eval_accuracy_kit import GSM8KMixin
from sglang.test.test_utils import CustomTestCase, popen_launch_server

# E2E test for Qwen3.5-397B-A17B W8A8-INT8 on PPU with NEXTN speculative
# decoding + DP attention (TP=16, DP=8, DeepEP a2a, GDN linear attention).
#
# This configuration reproduces the crash:
#   RuntimeError: cannot reshape tensor of 0 elements into shape [0, -1]
#   because the unspecified dimension size -1 can be any value and is ambiguous
# raised from Qwen3_5GatedDeltaNet.forward, plus the companion GemmaRMSNorm
# "invalid configuration argument" failure in Qwen3_5ForCausalLMMTP.forward:
# with --enable-dp-attention a DP rank can receive a non-idle ForwardBatch that
# carries 0 tokens, and the Qwen3.5 decoder layers / MTP head only skipped work
# for ForwardMode.IDLE, so per-token kernels still ran on 0-row inputs.
#
# The test verifies the server boots, survives the mixed prefill/verify traffic
# generated by GSM8K, and keeps speculative decoding accuracy intact.

MODEL_PATH = os.environ.get("MODEL_PATH", "modelscope.cn/organization/T-HEAD/Qwen3.5-397B-A17B-W8A8-INT8")
SERVED_MODEL_NAME = "Qwen3.5-397B-A17B"
BASE_URL = "http://127.0.0.1:8999"
SERVER_LAUNCH_TIMEOUT = 24000

# Local GSM8K dataset path — set GSM8K_DATA_PATH env var to avoid
# re-downloading the dataset on every run.
GSM8K_DATA_PATH = os.environ.get("GSM8K_DATA_PATH", None)


class TestQwen35397bA17bPpuNextnDpAttn(GSM8KMixin, CustomTestCase):
    """E2E: Qwen3.5-397B-A17B W8A8-INT8 NEXTN speculative decoding on PPU.

    TP=16 with DP attention (DP=8), DeepEP all-to-all MoE, fa3 target attention
    and triton draft attention. Guards against zero-token DP-attention batches
    aborting the target / MTP forward pass.
    """

    # --- GSM8KMixin config ---
    model = SERVED_MODEL_NAME
    gsm8k_score_threshold = 0.50
    gsm8k_num_examples = 200
    gsm8k_accept_length_thres = 1.0
    gsm8k_data_path = GSM8K_DATA_PATH

    # --- server launch config ---
    @classmethod
    def setUpClass(cls):
        other_args = [
            "--tp-size",
            "16",
            "--attention-backend",
            "fa3",
            "--mem-fraction-static",
            "0.8",
            "--speculative-algorithm",
            "NEXTN",
            "--speculative-num-steps",
            "2",
            "--speculative-eagle-topk",
            "1",
            "--speculative-num-draft-tokens",
            "3",
            "--speculative-draft-attention-backend",
            "triton",
            "--disable-radix-cache",
            "--deepep-mode",
            "auto",
            "--enable-dp-attention",
            "--dp-size",
            "8",
            "--quantization",
            "w8a8_int8",
            "--trust-remote-code",
            "--max-running-requests",
            "256",
            "--dist-timeout",
            "6000",
            "--enable-dp-lm-head",
            "--watchdog-timeout",
            "6000",
            "--soft-watchdog-timeout",
            "6000",
            "--reasoning-parser",
            "qwen3",
            "--moe-a2a-backend",
            "deepep",
            "--moe-dense-tp-size",
            "1",
            "--mamba-scheduler-strategy",
            "no_buffer",
            "--served-model-name",
            SERVED_MODEL_NAME,
        ]
        cls.process = popen_launch_server(
            MODEL_PATH,
            BASE_URL,
            timeout=SERVER_LAUNCH_TIMEOUT,
            other_args=other_args,
            env=os.environ,
        )

    @classmethod
    def tearDownClass(cls):
        kill_process_tree(cls.process.pid)

    @property
    def base_url(self):
        return BASE_URL


if __name__ == "__main__":
    unittest.main()
